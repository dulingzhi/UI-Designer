import { describe, it, expect } from 'vitest';
import { FDFExporter, FDFExporterEnhanced } from './fdfExporter';
import { FrameData, FrameType, FramePoint } from '../types';

/** Minimal, fully-populated FrameData factory. */
function mkFrame(partial: Partial<FrameData> & { id: string; name: string }): FrameData {
  return {
    type: FrameType.FRAME,
    x: 0,
    y: 0,
    width: 0,
    height: 0,
    z: 0,
    parentId: null,
    children: [],
    anchors: [],
    texture: '',
    ...partial,
  };
}

/** Subclass that exposes protected/private members for direct branch control. */
class TestableExporter extends FDFExporter {
  public getIndentPub(): string {
    return this.getIndent();
  }
  public toRelativePub(pixels: number, base: number): string {
    return this.toRelative(pixels, base);
  }
  public mapFrameTypePub(type: number): string {
    return this.mapFrameType(type);
  }
  public mapFramePointToNamePub(point: number): string {
    return this.mapFramePointToName(point);
  }
  public mapHorizontalAlignPub(align: string): string {
    return this.mapHorizontalAlign(align);
  }
  public mapVerticalAlignPub(align: string): string {
    return this.mapVerticalAlign(align);
  }
  public hexToRgbaPub(hex: string) {
    return this.hexToRgba(hex);
  }
  public escapeStringPub(value: unknown): string {
    return this.escapeString(value);
  }
}

describe('FDFExporter', () => {
  it('constructs with default options', () => {
    const e = new FDFExporter();
    expect(e).toBeInstanceOf(FDFExporter);
  });

  it('exports empty array with comments header', () => {
    const e = new FDFExporter();
    const out = e.export([]);
    expect(out).toContain('// Generated by WC3 UI Designer');
    expect(out).toMatch(/\/\/ 20\d\d-/);
  });

  it('omits header when includeComments=false', () => {
    const e = new FDFExporter({ includeComments: false });
    const out = e.export([mkFrame({ id: 'a', name: 'A' })]);
    expect(out).not.toContain('Generated by');
    expect(out).toContain('Frame "FRAME" "A" {');
  });

  it('exports multiple frames separated by newline', () => {
    const e = new FDFExporter({ includeComments: false });
    const out = e.export([
      mkFrame({ id: 'a', name: 'A' }),
      mkFrame({ id: 'b', name: 'B' }),
    ]);
    expect(out).toMatch(/Frame "FRAME" "A" \{\s*\}\n\nFrame "FRAME" "B"/);
  });

  it('renders INHERITS and fallback frame name from id', () => {
    const e = new FDFExporter({ includeComments: false });
    const out = e.export([mkFrame({ id: 'xyz', name: '', fdfMetadata: { inherits: 'Base' } })]);
    expect(out).toContain('Frame "FRAME" "Frame_xyz" INHERITS "Base" {');
  });

  it('renders SetPoint for relative anchor and Anchor for absolute anchor', () => {
    const e = new FDFExporter({ includeComments: false });
    const frame = mkFrame({
      id: 'c',
      name: 'Child',
      width: 0.5,
      height: 0.25,
      anchors: [
        { point: FramePoint.CENTER, relativeTo: 'p', relativePoint: FramePoint.CENTER, x: 0.1, y: 0.2 },
        { point: FramePoint.LEFT, x: 0.3, y: 0.4 },
      ],
    });
    const out = e.export([frame]);
    expect(out).toContain('SetPoint CENTER, "p", CENTER, 0.000125, 0.000333');
    expect(out).toContain('Anchor LEFT, 0.000375, 0.000667');
    expect(out).toContain('Width 0.000625');
    expect(out).toContain('Height 0.000417');
  });

  it('renders text, textColor, alignments, texture, backdropBackground', () => {
    const e = new FDFExporter({ includeComments: false });
    const frame = mkFrame({
      id: 'f',
      name: 'F',
      text: 'Hello',
      textColor: '#ffffff',
      horAlign: 'right',
      verAlign: 'start',
      texture: 'bg.blp',
      backdropBackground: 'back.blp',
    });
    const out = e.export([frame]);
    expect(out).toContain('Text "Hello"');
    expect(out).toContain('FontColor 1 1 1 1');
    expect(out).toContain('FontJustificationH JUSTIFYRIGHT');
    expect(out).toContain('FontJustificationV JUSTIFYTOP');
    expect(out).toContain('Texture {');
    expect(out).toContain('File "bg.blp"');
    expect(out).toContain('BackdropBackground "back.blp"');
  });
it('renders SetPoint with falsy relativePoint (TOPLEFT=0) via || default', () => {
    const e = new FDFExporter({ includeComments: false });
    const frame = mkFrame({
      id: 'c',
      name: 'Child',
      anchors: [{ point: FramePoint.TOP, relativeTo: 'p', relativePoint: 0, x: 0, y: 0 }],
    });
    const out = e.export([frame]);
    expect(out).toContain('SetPoint TOP, "p", TOPLEFT, 0.000000, 0.000000');
  });
});

