class TestableEnhanced extends FDFExporterEnhanced {
  public frameMapForKey(id: string) {
    return (this as any).frameMap.get(id);
  }
}

describe('FDFExporterEnhanced', () => {
  it('constructs with default enhanced options', () => {
    const e = new FDFExporterEnhanced();
    expect(e).toBeInstanceOf(FDFExporterEnhanced);
  });

  it('exports only top-level frames, exporting nested children recursively', () => {
    const parent = mkFrame({ id: 'p', name: 'Parent', children: ['c', 'gc'] });
    const child = mkFrame({ id: 'c', name: 'Child', parentId: 'p', children: ['gc'] });
    const gc = mkFrame({ id: 'gc', name: 'GrandChild', parentId: 'c', width: 0.2, height: 0.1, children: [] });
    const e = new FDFExporterEnhanced({ includeComments: true });
    const out = e.exportEnhanced([parent, child, gc]);
    expect(out).toContain('// Generated by WC3 UI Designer (Enhanced Export)');
    expect(out).toContain('// Lossless export with metadata preservation');
    expect(out).toContain('Frame "FRAME" "Parent" {');
    expect(out).toContain('Frame "FRAME" "Child" {');
    expect(out).toContain('Frame "FRAME" "GrandChild" {');
  });

  it('exports nested frames and missing child gracefully', () => {
    const parent = mkFrame({ id: 'p', name: 'Parent', children: ['c1', 'ghost'] });
    const c1 = mkFrame({ id: 'c1', name: 'Child1', parentId: 'p', width: 0.1, height: 0.2 });
    const te = new TestableEnhanced({ includeComments: false });
    const out = te.exportEnhanced([parent, c1]);
    expect(out).toContain('Child1');
    // ghost has no matching frame -> skipped silently, no crash
    expect(te.frameMapForKey('c1')).toBeDefined();
  });

  it('exports without comments and builds frame map', () => {
    const e = new TestableEnhanced({ includeComments: false, lossless: false });
    const out = e.exportEnhanced([mkFrame({ id: 'x', name: 'X' })]);
    expect(out).not.toContain('Generated by');
    expect(out).toContain('Frame "FRAME" "X" {');
  });

  it('handles empty frame array', () => {
    const e = new FDFExporterEnhanced({ includeComments: true });
    const out = e.exportEnhanced([]);
    expect(out).toContain('// Generated by WC3 UI Designer (Enhanced Export)');
  });
});

describe('FDFExporterEnhanced property export', () => {
  it('exports raw properties (array, object, string, number) plus runtime-only props', () => {
    const frame = mkFrame({
      id: 'f',
      name: 'F',
      width: 0.5,
      fdfMetadata: {
        rawProperties: {
          ArrProp: [1, 2],
          ObjProp: { File: 'tex.blp', TexCoord: [0, 1, 0, 1] },
          StrProp: 'he"llo',
          NumProp: 42,
          // intentionally leave width/height unset so runtime props are exported
        },
      },
    });
    const e = new FDFExporterEnhanced({ includeComments: false });
    const out = e.exportEnhanced([frame]);
    expect(out).toContain('ArrProp 1, 2');
    expect(out).toContain('ObjProp {');
    expect(out).toContain('File "tex.blp"');
    expect(out).toContain('StrProp "he\\"llo"');
    expect(out).toContain('NumProp 42');
    expect(out).toContain('Width 0.000625');
  });

  it('exportRuntimeProperties emits anchors, text, colors, alignments, texture, backdrop', () => {
    const frame = mkFrame({
      id: 'f',
      name: 'F',
      anchors: [
        { point: FramePoint.TOP, relativeTo: 'p', relativePoint: FramePoint.TOP, x: 0.1, y: 0.2 },
        { point: FramePoint.BOTTOMLEFT, x: 0.3, y: 0.4 },
      ],
      text: 'hello',
      textColor: '#ff0000ff',
      horAlign: 'left',
      verAlign: 'flex-end',
      texture: 'tex.blp',
      backdropBackground: 'bg.blp',
    });
    const e = new FDFExporterEnhanced({ includeComments: false });
    const out = e.exportEnhanced([frame]);
    expect(out).toContain('SetPoint TOP, "p", TOP, 0.000125, 0.000333');
    expect(out).toContain('Anchor BOTTOMLEFT, 0.000375, 0.000667');
    expect(out).toContain('Text "hello"');
    expect(out).toContain('FontColor 1 0 0 1');
    expect(out).toContain('FontJustificationH JUSTIFYLEFT');
    expect(out).toContain('FontJustificationV JUSTIFYBOTTOM');
    expect(out).toContain('Texture {');
    expect(out).toContain('BackdropBackground "bg.blp"');
  });

  it('skips exported props when already present in rawProperties', () => {
    const frame = mkFrame({
      id: 'f',
      name: 'F',
      width: 0.9,
      text: 'should-not-appear',
      anchors: [{ point: FramePoint.CENTER, x: 0, y: 0 }],
      fdfMetadata: {
        rawProperties: {
          width: '0.1', // lowercase key marks as exported
          text: 'orig',
          setpoint: 'orig',
        },
      },
    });
    const e = new FDFExporterEnhanced({ includeComments: false });
    const out = e.exportEnhanced([frame]);
    expect(out).not.toContain('Width');
    expect(out).not.toContain('Text "should-not-appear"');
    // setpoint exported -> anchors not emitted
    expect(out).not.toContain('Anchor');
  });

  it('exports in standard mode (lossless=false) using runtime props only', () => {
    const frame = mkFrame({
      id: 'f',
      name: 'F',
      width: 0.5,
      height: 0.1,
      fdfMetadata: { rawProperties: { width: 'x' } },
    });
    const e = new FDFExporterEnhanced({ includeComments: false, lossless: false, mergeRawProperties: true });
    const out = e.exportEnhanced([frame]);
    // lossless off -> rawProps not exported, width emitted (relative to base 800)
    expect(out).toContain('Width 0.000625');
  });

  it('exportTexture uses fdfTexture fully and falls back to plain texture', () => {
    const full = mkFrame({
      id: 'full',
      name: 'Full',
      fdfTexture: {
        file: 'tex.blp',
        texCoord: [0, 1, 0, 1],
        alphaMode: 'BLEND',
        decorateFileNames: true,
      },
    });
    const plain = mkFrame({ id: 'plain', name: 'Plain', texture: 'simple.blp' });
    const e = new FDFExporterEnhanced({ includeComments: false, lossless: false });
    const out = e.exportEnhanced([full, plain]);
    expect(out).toContain('File "tex.blp"');
    expect(out).toContain('TexCoord 0, 1, 0, 1');
    expect(out).toContain('AlphaMode "BLEND"');
    expect(out).toContain('DecorateFileNames true');
    expect(out).toContain('File "simple.blp"');
  });

  it('exportTexture with fdfTexture lacking optional fields', () => {
    const frame = mkFrame({
      id: 'f',
      name: 'F',
      fdfTexture: { file: 'tex.blp' },
    });
    const e = new FDFExporterEnhanced({ includeComments: false });
    const out = e.exportEnhanced([frame]);
    expect(out).toContain('File "tex.blp"');
    expect(out).not.toContain('TexCoord');
    expect(out).not.toContain('AlphaMode');
    expect(out).not.toContain('DecorateFileNames');
  });

  it('enhanced export falls back to id-based frame name when name empty', () => {
    const e = new FDFExporterEnhanced({ includeComments: false, lossless: true, mergeRawProperties: true });
    const out = e.exportEnhanced([mkFrame({ id: 'myId', name: '' })]);
    expect(out).toContain('Frame "FRAME" "Frame_myId" {');
  });

  it('enhanced export renders SetPoint with default relativePoint when 0', () => {
    const e = new FDFExporterEnhanced({ includeComments: false, lossless: true, mergeRawProperties: true });
    const frame = mkFrame({
      id: 'c',
      name: 'Child',
      anchors: [{ point: FramePoint.TOP, relativeTo: 'p', relativePoint: 0, x: 0.1, y: 0.2 }],
    });
    const out = e.exportEnhanced([frame]);
    expect(out).toContain('SetPoint TOP, "p", TOPLEFT');
  });

  it('enhanced export falls back to plain texture when no fdfTexture', () => {
    const e = new FDFExporterEnhanced({ includeComments: false, lossless: true, mergeRawProperties: true });
    const out = e.exportEnhanced([mkFrame({ id: 'p', name: 'P', texture: 'plain.blp' })]);
    expect(out).toContain('File "plain.blp"');
  });

  it('enhanced export emits nothing for texture when neither present', () => {
    const e = new FDFExporterEnhanced({ includeComments: false, lossless: true, mergeRawProperties: true });
    const out = e.exportEnhanced([mkFrame({ id: 'p', name: 'P' })]);
    expect(out).not.toContain('Texture');
  });

  it('exportFrameEnhanced renders comment and INHERITS', () => {
    const frame = mkFrame({
      id: 'f',
      name: 'F',
      fdfMetadata: { comment: 'My Comment', inherits: 'Base' },
    });
    const e = new FDFExporterEnhanced({ includeComments: false });
    const out = e.exportEnhanced([frame]);
    expect(out).toContain('// My Comment');
    expect(out).toContain('Frame "FRAME" "F" INHERITS "Base" {');
  });
});