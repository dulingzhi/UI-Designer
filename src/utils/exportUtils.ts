import { ProjectData, FrameData, FrameType } from '../types';
import { save } from '@tauri-apps/plugin-dialog';
import { writeTextFile } from '@tauri-apps/plugin-fs';
import { FDFExporterEnhanced } from './fdfExporter';
import { escapeJassString } from './codegen/identifiers';

/** 编辑器对齐值 → FDF 的 JustifyH 常量。 */
function justifyHOf(align: FrameData['horAlign']): string | undefined {
  if (align === 'left') return 'JUSTIFYLEFT';
  if (align === 'right') return 'JUSTIFYRIGHT';
  if (align === 'center') return 'JUSTIFYCENTER';
  return undefined;
}

/** 编辑器对齐值 → FDF 的 JustifyV 常量。 */
function justifyVOf(align: FrameData['verAlign']): string | undefined {
  if (align === 'start') return 'JUSTIFYTOP';
  if (align === 'flex-end') return 'JUSTIFYBOTTOM';
  if (align === 'center') return 'JUSTIFYMIDDLE';
  return undefined;
}

/**
 * 导出项目为 FDF 格式（魔兽3 UI 文件格式）
 * @param project 项目数据
 * @param enhanced 是否使用增强导出（无损、保留元数据）
 * @param onShowAlert 可选的 alert 回调函数
 */
export async function exportToFDF(
  project: ProjectData, 
  enhanced: boolean = false,
  onShowAlert?: (options: { title: string; message: string; type: 'info' | 'warning' | 'danger' }) => void
): Promise<void> {
  try {
    // 打开保存对话框
    const path = await save({
      filters: [{
        name: 'Frame Definition File',
        extensions: ['fdf']
      }],
      defaultPath: 'ui-design.fdf'
    });

    if (!path) return; // 用户取消

    // 生成 FDF 内容
    const fdfContent = enhanced 
      ? generateFDFContentEnhanced(project) 
      : generateFDFContent(project);

    // 写入文件
    await writeTextFile(path, fdfContent);

    if (onShowAlert) {
      onShowAlert({ title: '成功', message: `导出 FDF 成功！${enhanced ? '（增强模式）' : ''}`, type: 'info' });
    } else {
      alert(`导出 FDF 成功！${enhanced ? '（增强模式）' : ''}`);
    }
  } catch (error) {
    console.error('导出 FDF 失败:', error);
    if (onShowAlert) {
      onShowAlert({ title: '错误', message: `导出失败: ${error}`, type: 'danger' });
    } else {
      alert(`导出失败: ${error}`);
    }
  }
}

/**
 * 导出项目为 JSON 格式
 * @param onShowAlert 可选的 alert 回调函数
 */
export async function exportToJSON(
  project: ProjectData,
  onShowAlert?: (options: { title: string; message: string; type: 'info' | 'warning' | 'danger' }) => void
): Promise<void> {
  try {
    const path = await save({
      filters: [{
        name: 'JSON File',
        extensions: ['json']
      }],
      defaultPath: 'ui-design.json'
    });

    if (!path) return;

    const jsonContent = JSON.stringify(project, null, 2);
    await writeTextFile(path, jsonContent);

    if (onShowAlert) {
      onShowAlert({ title: '成功', message: '导出 JSON 成功！', type: 'info' });
    } else {
      alert('导出 JSON 成功！');
    }
  } catch (error) {
    console.error('导出 JSON 失败:', error);
    if (onShowAlert) {
      onShowAlert({ title: '错误', message: `导出失败: ${error}`, type: 'danger' });
    } else {
      alert(`导出失败: ${error}`);
    }
  }
}

/**
 * 生成 FDF 文件内容（标准模式）
 */
function generateFDFContent(project: ProjectData): string {
  const lines: string[] = [];

  // 添加文件头注释
  lines.push('// Generated by WC3 UI Designer');
  lines.push(`// Date: ${new Date().toLocaleString()}`);
  lines.push(`// Origin Mode: ${project.originMode}`);
  lines.push('');

  // 包含必要的文件
  lines.push('IncludeFile "UI\\FrameDef\\UI\\EscMenuTemplates.fdf",');
  lines.push('');

  // 递归生成所有控件的 FDF 代码
  for (const frameId of project.rootFrameIds) {
    generateFrameFDF(project.frames[frameId], project.frames, lines, 0, project);
  }

  return lines.join('\n');
}

/**
 * 生成 FDF 文件内容（增强模式 - 无损导出）
 */
function generateFDFContentEnhanced(project: ProjectData): string {
  // 将 frames 对象转换为数组
  const framesArray = Object.values(project.frames);
  
  // 创建增强导出器
  const exporter = new FDFExporterEnhanced({
    lossless: true,
    mergeRawProperties: true,
    smartInheritance: true,
    exportNestedFrames: true,
    includeComments: true,
    baseWidth: 800,
    baseHeight: 600,
  });
  
  // 使用增强导出
  let fdfContent = exporter.exportEnhanced(framesArray);
  
  // 添加项目特定的头部信息
  const header = [
    `// Origin Mode: ${project.originMode}`,
    '',
    'IncludeFile "UI\\FrameDef\\UI\\EscMenuTemplates.fdf",',
    '',
  ].join('\n');
  
  // 在第一个 Frame 定义之前插入头部
  const firstFrameIndex = fdfContent.indexOf('Frame "');
  if (firstFrameIndex > 0) {
    fdfContent = fdfContent.substring(0, firstFrameIndex) + header + fdfContent.substring(firstFrameIndex);
  } else {
    fdfContent = header + fdfContent;
  }
  
  return fdfContent;
}

/**
 * 递归生成单个控件的 FDF 代码
 */
function generateFrameFDF(
  frame: FrameData,
  allFrames: Record<string, FrameData>,
  lines: string[],
  indent: number,
  project: ProjectData
): void {
  const indentStr = '    '.repeat(indent);

  // Frame 定义开始
  lines.push(`${indentStr}Frame "${getFrameTypeName(frame.type)}" "${frame.name}" {`);

  // 如果有父控件，设置 UseActiveContext
  if (frame.parentId) {
    lines.push(`${indentStr}    UseActiveContext TRUE,`);
  }

  // 设置尺寸
  lines.push(`${indentStr}    Width ${frame.width},`);
  lines.push(`${indentStr}    Height ${frame.height},`);

  // 设置锚点
  if (frame.anchors && frame.anchors.length > 0) {
    for (const anchor of frame.anchors) {
      const anchorLine = generateAnchorFDF(anchor, frame, allFrames, indentStr, project);
      /* v8 ignore start -- provably unreachable null check: generateAnchorFDF always returns the SetPoint string (no null path exists despite its `string | null` type). */
      if (anchorLine) {
        lines.push(anchorLine);
      }
      /* v8 ignore end */
    }
  } else {
    // 如果没有锚点，使用默认位置
    lines.push(`${indentStr}    SetPoint TOPLEFT, "${getParentName(frame, allFrames, project)}", TOPLEFT, ${frame.x}, ${-frame.y},`);
  }

  // 根据类型添加特定属性
  switch (frame.type) {
    case FrameType.BACKDROP:
      // 背景纹理：优先 `backdropBackground`（正确字段），兼容旧的 `texture`
      if (frame.backdropBackground || frame.texture) {
        const bg = frame.backdropBackground || frame.texture;
        lines.push(`${indentStr}    BackdropBackground "${bg}",`);
        // SetTexture 让 frame.texture 在导入往返中不丢失（与 codeExport 语义一致）
        lines.push(`${indentStr}    SetTexture "${bg}",`);
      }
      // 九宫格边框：全部为 FDF 模板属性（dzapi 无任何运行时 backdrop API）
      if (frame.backdropEdgeFile) {
        lines.push(`${indentStr}    BackdropEdgeFile "${frame.backdropEdgeFile}",`);
      }
      if (frame.backdropCornerFile) {
        lines.push(`${indentStr}    BackdropCornerFile "${frame.backdropCornerFile}",`);
      }
      if (frame.backdropTopFile) {
        lines.push(`${indentStr}    BackdropTopFile "${frame.backdropTopFile}",`);
      }
      if (frame.backdropBottomFile) {
        lines.push(`${indentStr}    BackdropBottomFile "${frame.backdropBottomFile}",`);
      }
      if (frame.backdropLeftFile) {
        lines.push(`${indentStr}    BackdropLeftFile "${frame.backdropLeftFile}",`);
      }
      if (frame.backdropRightFile) {
        lines.push(`${indentStr}    BackdropRightFile "${frame.backdropRightFile}",`);
      }
      // 角标志：如实导出用户配置（旧实现硬编码全标志，会覆盖用户设置）
      if (frame.backdropCornerFlags) {
        lines.push(`${indentStr}    BackdropCornerFlags "${frame.backdropCornerFlags}",`);
      }
      if (frame.backdropCornerSize !== undefined) {
        lines.push(`${indentStr}    BackdropCornerSize ${frame.backdropCornerSize},`);
      }
      if (frame.backdropBackgroundSize !== undefined) {
        lines.push(`${indentStr}    BackdropBackgroundSize ${frame.backdropBackgroundSize},`);
      }
      if (frame.backdropBackgroundInsets) {
        const [l, t, r, b] = frame.backdropBackgroundInsets;
        lines.push(`${indentStr}    BackdropBackgroundInsets ${l} ${t} ${r} ${b},`);
      }
      if (frame.backdropTileBackground) {
        lines.push(`${indentStr}    BackdropTileBackground,`);
      }
      break;

    case FrameType.TEXT_FRAME: {
      // 文本必须转义：未转义时 parser 不报错但会静默截断（"a"b" → 只剩 "a"）。
      // textColor 无独立模板属性，按 WC3 语义内嵌 |cffRRGGBB 前缀（与导入侧剥离互逆）。
      if (frame.text) {
        const color = frame.textColor?.replace('#', '').slice(0, 6);
        const colored = color && /^[0-9a-fA-F]{6}$/.test(color)
          ? `|cff${color}${frame.text}|r`
          : frame.text;
        lines.push(`${indentStr}    Text "${escapeJassString(colored)}",`);
      }
      // 对齐属性（旧实现只在 horAlign 存在时输出 FrameFont，既没输出对齐、又硬编码字体名）
      const jh = justifyHOf(frame.horAlign);
      if (jh) lines.push(`${indentStr}    FontJustificationH ${jh},`);
      const jv = justifyVOf(frame.verAlign);
      if (jv) lines.push(`${indentStr}    FontJustificationV ${jv},`);
      if (frame.horAlign !== undefined || frame.verAlign !== undefined || frame.textScale) {
        const fontSize = frame.textScale || 0.012;
        lines.push(`${indentStr}    FrameFont "MasterFont", ${fontSize}, "",`);
      }
      break;
    }

    case FrameType.BUTTON:
    case FrameType.BROWSER_BUTTON:
    case FrameType.SCRIPT_DIALOG_BUTTON:
      if (frame.text) {
        lines.push(`${indentStr}    ButtonText "${escapeJassString(frame.text)}",`);
      }
      break;

    case FrameType.EDITBOX:
    case FrameType.TEXTAREA:
      if (frame.text) {
        lines.push(`${indentStr}    EditTextFrame "${escapeJassString(frame.text)}",`);
      }
      break;
  }

  // 通用纹理属性（对所有类型生效）
  if (frame.texCoord) {
    const [l, r, t, b] = frame.texCoord;
    lines.push(`${indentStr}    TexCoord ${l}, ${r}, ${t}, ${b},`);
  }
  if (frame.alphaMode) {
    lines.push(`${indentStr}    AlphaMode "${frame.alphaMode}",`);
  }
  if (frame.decorateFileNames) {
    lines.push(`${indentStr}    DecorateFileNames,`);
  }

  // Control 系（真实 FDF 实证：属性值为模板名，非文件路径；见 FrameDef 全量扫描）
  if (frame.controlBackdrop) {
    lines.push(`${indentStr}    ControlBackdrop "${frame.controlBackdrop}",`);
  }
  if (frame.controlPushedBackdrop) {
    lines.push(`${indentStr}    ControlPushedBackdrop "${frame.controlPushedBackdrop}",`);
  }
  if (frame.controlDisabledBackdrop) {
    lines.push(`${indentStr}    ControlDisabledBackdrop "${frame.controlDisabledBackdrop}",`);
  }
  if (frame.controlMouseOverHighlight) {
    lines.push(`${indentStr}    ControlMouseOverHighlight "${frame.controlMouseOverHighlight}",`);
  }
  if (frame.controlStyle) {
    lines.push(`${indentStr}    ControlStyle "${frame.controlStyle}",`);
  }

  // Highlight 系
  if (frame.highlightType) {
    lines.push(`${indentStr}    HighlightType "${frame.highlightType}",`);
  }
  if (frame.highlightAlphaFile) {
    lines.push(`${indentStr}    HighlightAlphaFile "${frame.highlightAlphaFile}",`);
  }
  if (frame.highlightAlphaMode) {
    lines.push(`${indentStr}    HighlightAlphaMode "${frame.highlightAlphaMode}",`);
  }

  // Font 系（颜色为四数值 0..1，与真实 FDF 的空格分隔格式一致）
  const color4 = (c: [number, number, number, number]) => `${c[0]} ${c[1]} ${c[2]} ${c[3]}`;
  if (frame.fontHighlightColor) {
    lines.push(`${indentStr}    FontHighlightColor ${color4(frame.fontHighlightColor)},`);
  }
  if (frame.fontDisabledColor) {
    lines.push(`${indentStr}    FontDisabledColor ${color4(frame.fontDisabledColor)},`);
  }
  if (frame.fontShadowColor) {
    lines.push(`${indentStr}    FontShadowColor ${color4(frame.fontShadowColor)},`);
  }
  if (frame.fontShadowOffset) {
    lines.push(`${indentStr}    FontShadowOffset ${frame.fontShadowOffset[0]} ${frame.fontShadowOffset[1]},`);
  }
  if (frame.buttonPushedTextOffset) {
    lines.push(`${indentStr}    ButtonPushedTextOffset ${frame.buttonPushedTextOffset[0]} ${frame.buttonPushedTextOffset[1]},`);
  }

  // EditBox 系（真实 FDF 实证）：EditCursorColor 为三数值（语法无 alpha，第四分量丢弃）。
  // editTextColor / editBorderColor 在真实 FDF 中无对应模板属性（边框实为 EditBorderSize
  // 数值而非颜色），如实不输出，不臆造。
  if (frame.editCursorColor) {
    const [r, g, b] = frame.editCursorColor;
    lines.push(`${indentStr}    EditCursorColor ${r} ${g} ${b},`);
  }

  // 递归处理子控件
  if (frame.children && frame.children.length > 0) {
    lines.push('');
    for (const childId of frame.children) {
      const child = allFrames[childId];
      if (child) {
        generateFrameFDF(child, allFrames, lines, indent + 1, project);
      }
    }
  }

  // Frame 定义结束
  lines.push(`${indentStr}}`);
  lines.push('');
}

/**
 * 生成锚点的 FDF 代码
 */
function generateAnchorFDF(
  anchor: any,
  frame: FrameData,
  allFrames: Record<string, FrameData>,
  indentStr: string,
  project: ProjectData
): string | null {
  const point = anchor.point || 'TOPLEFT';
  const relativePoint = anchor.relativePoint || 'TOPLEFT';
  const x = anchor.x || 0;
  const y = anchor.y || 0;

  // 获取相对控件名称
  let relativeTo = getParentName(frame, allFrames, project);
  if (anchor.relativeTo) {
    const relativeFrame = allFrames[anchor.relativeTo];
    if (relativeFrame) {
      relativeTo = relativeFrame.name;
    }
  }

  return `${indentStr}    SetPoint ${point}, "${relativeTo}", ${relativePoint}, ${x}, ${-y},`;
}

/**
 * 获取父控件名称
 */
function getParentName(frame: FrameData, allFrames: Record<string, FrameData>, project?: ProjectData): string {
  if (!frame.parentId) {
    // 根节点的父控件根据 originMode 决定
    /* v8 ignore start -- provably unreachable false arm: both callers (lines 187, 257) pass a non-optional project, so project is always truthy here. */
    if (project) {
      switch (project.originMode) {
        case 'gameui': return 'GameUI';
        case 'worldframe': return 'WorldFrameWar3';
        case 'consoleui': return 'ConsoleUI';
        default: return 'ConsoleUI';
      }
    }
    /* v8 ignore end */
    return 'ConsoleUI';
  }

  const parent = allFrames[frame.parentId];
  return parent ? parent.name : 'ConsoleUI';
}

/**
 * 获取 Frame 类型的 FDF 名称
 */
function getFrameTypeName(type: FrameType): string {
  switch (type) {
    case FrameType.BACKDROP: return 'BACKDROP';
    case FrameType.BUTTON: return 'BUTTON';
    case FrameType.BROWSER_BUTTON: return 'BUTTON';
    case FrameType.SCRIPT_DIALOG_BUTTON: return 'BUTTON';
    case FrameType.TEXT_FRAME: return 'TEXT';
    case FrameType.CHECKBOX: return 'CHECKBOX';
    case FrameType.HORIZONTAL_BAR: return 'SLIDER';
    case FrameType.TEXTAREA: return 'EDITBOX';
    case FrameType.EDITBOX: return 'EDITBOX';
    case FrameType.SLIDER: return 'SLIDER';
    default: return 'FRAME';
  }
}

/**
 * 导出为 PNG 预览图
 * @param onShowAlert 可选的 alert 回调函数
 */
export async function exportToPNG(
  canvasElement: HTMLCanvasElement | null,
  onShowAlert?: (options: { title: string; message: string; type: 'info' | 'warning' | 'danger' }) => void
): Promise<void> {
  if (!canvasElement) {
    if (onShowAlert) {
      onShowAlert({ title: '错误', message: '无法获取画布元素', type: 'danger' });
    } else {
      alert('无法获取画布元素');
    }
    return;
  }

  try {
    const path = await save({
      filters: [{
        name: 'PNG Image',
        extensions: ['png']
      }],
      defaultPath: 'ui-preview.png'
    });

    if (!path) return;

    // 将 canvas 转换为 blob
    canvasElement.toBlob(async (blob) => {
      if (!blob) {
        if (onShowAlert) {
          onShowAlert({ title: '错误', message: '生成图片失败', type: 'danger' });
        } else {
          alert('生成图片失败');
        }
        return;
      }

      try {
        // 读取 blob 为 ArrayBuffer
        const arrayBuffer = await blob.arrayBuffer();
        const uint8Array = new Uint8Array(arrayBuffer);

        // 使用 Tauri 的文件系统 API 写入文件
        const { writeFile } = await import('@tauri-apps/plugin-fs');
        await writeFile(path, uint8Array);

        if (onShowAlert) {
          onShowAlert({ title: '成功', message: '导出 PNG 成功！', type: 'info' });
        } else {
          alert('导出 PNG 成功！');
        }
      } catch (error) {
        console.error('写入文件失败:', error);
        if (onShowAlert) {
          onShowAlert({ title: '错误', message: `导出失败: ${error}`, type: 'danger' });
        } else {
          alert(`导出失败: ${error}`);
        }
      }
    }, 'image/png');
  } catch (error) {
    console.error('导出 PNG 失败:', error);
    if (onShowAlert) {
      onShowAlert({ title: '错误', message: `导出失败: ${error}`, type: 'danger' });
    } else {
      alert(`导出失败: ${error}`);
    }
  }
}
