import { describe, it, expect, vi, beforeEach } from 'vitest';
import { exportToFDF, exportToJSON, exportToPNG } from './exportUtils';
import { FrameType, FramePoint, type ProjectData, type FrameData } from '../types';

// --- Mocks ---
const fdfMocks = vi.hoisted(() => ({ exportEnhanced: vi.fn() }));
const dialogMocks = vi.hoisted(() => ({ save: vi.fn() }));
const fsMocks = vi.hoisted(() => ({
  writeTextFile: vi.fn(),
  writeFile: vi.fn(),
  mkdir: vi.fn(),
}));

vi.mock('@tauri-apps/plugin-dialog', () => ({ save: dialogMocks.save }));
vi.mock('@tauri-apps/plugin-fs', () => ({ writeTextFile: fsMocks.writeTextFile, writeFile: fsMocks.writeFile }));

vi.mock('./fdfExporter', () => ({
  FDFExporterEnhanced: function FDFExporterEnhanced() {
    this.exportEnhanced = fdfMocks.exportEnhanced;
  },
}));

function makeProject(overrides: Partial<ProjectData> = {}): ProjectData {
  return {
    version: 2,
    libraryName: 'TestLib',
    originMode: 'gameui',
    exportVersion: 'reforged',
    hideGameUI: false,
    hideHeroBar: false,
    hideMiniMap: false,
    hideResources: false,
    hideButtonBar: false,
    hidePortrait: false,
    hideChat: false,
    frames: {},
    rootFrameIds: [],
    tableArrays: [],
    circleArrays: [],
    ...overrides,
  };
}

function frame(overrides: Partial<FrameData> & { id: string; name: string; type: FrameType }): FrameData {
  return { x: 10, y: 20, width: 100, height: 50, z: 0, parentId: null, children: [], anchors: [], ...overrides };
}

// Standard-mode project exercising all generateFrameFDF / getParentName / getFrameTypeName branches.
function standardProject(originMode: ProjectData['originMode'] = 'gameui'): ProjectData {
  const anchorTarget = frame({ id: 'acct', name: 'AnchorTarget', type: FrameType.BUTTON, anchors: [] });
  const anchorTargetMissingChild = frame({
    id: 'missingChild', name: 'MissingParentChild', type: FrameType.BUTTON, parentId: 'does-not-exist', children: [],
  });
  const frames: Record<string, FrameData> = {
    root: frame({ id: 'root', name: 'RootMenu', type: FrameType.CHECKBOX, children: ['bkd', 'bkdNotex', 'text', 'textPlain', 'btn', 'btnNotext', 'edit', 'editNotext', 'anchorChild', 'anchorNoRel', 'acct', 'missingChild'] }),
    bkd: frame({ id: 'bkd', name: 'BackdropOn', type: FrameType.BACKDROP, texture: 'tex.blp', anchors: [{ point: FramePoint.TOPLEFT, x: 1, y: 2 }], parentId: 'root' }),
    bkdNotex: frame({ id: 'bkdNotex', name: 'BackdropOff', type: FrameType.BACKDROP, anchors: [], parentId: 'root' }),
    text: frame({ id: 'text', name: 'TextOn', type: FrameType.TEXT_FRAME, text: 'Hello', horAlign: 'center', textScale: 0.5, anchors: [], parentId: 'root' }),
    textPlain: frame({ id: 'textPlain', name: 'TextOff', type: FrameType.TEXT_FRAME, anchors: [], parentId: 'root' }),
    btn: frame({ id: 'btn', name: 'ButtonOn', type: FrameType.BUTTON, text: 'OK', anchors: [], parentId: 'root' }),
    btnNotext: frame({ id: 'btnNotext', name: 'ButtonOff', type: FrameType.BROWSER_BUTTON, anchors: [], parentId: 'root' }),
    edit: frame({ id: 'edit', name: 'EditOn', type: FrameType.EDITBOX, text: 'input', anchors: [], parentId: 'root' }),
    editNotext: frame({ id: 'editNotext', name: 'EditOff', type: FrameType.TEXTAREA, anchors: [], parentId: 'root' }),
    anchorChild: frame({
      id: 'anchorChild', name: 'RelChild', type: FrameType.TEXT_FRAME,
      anchors: [{ point: FramePoint.LEFT, relativeTo: 'anchorTargetRef', relativePoint: FramePoint.RIGHT }],
      parentId: 'root',
    }),
    anchorNoRel: frame({
      id: 'anchorNoRel', name: 'NoRelChild', type: FrameType.TEXT_FRAME,
      anchors: [{ point: FramePoint.TOP, x: 5, y: 7 }], parentId: 'root',
    }),
    acct: anchorTarget,
    missingChild: anchorTargetMissingChild,
  };
  frames.anchorChild.children = [];
  return makeProject({ originMode, frames, rootFrameIds: ['root'] });
}

describe('exportUtils', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    dialogMocks.save.mockReset();
    fsMocks.writeTextFile.mockReset();
    fsMocks.writeFile.mockReset();
    fdfMocks.exportEnhanced.mockReset();
    fdfMocks.exportEnhanced.mockReturnValue('');
  });

  describe('exportToFDF', () => {
    it('writes standard FDF and alerts on success via onShowAlert callback', async () => {
      dialogMocks.save.mockResolvedValue('/out/design.fdf');
      fsMocks.writeTextFile.mockResolvedValue(undefined as never);
      const onShowAlert = vi.fn();
      await exportToFDF(standardProject(), false, onShowAlert);
      expect(dialogMocks.save).toHaveBeenCalled();
      expect(fsMocks.writeTextFile).toHaveBeenCalledTimes(1);
      const [filePath, content] = fsMocks.writeTextFile.mock.calls[0];
      expect(filePath).toBe('/out/design.fdf');
      expect(content).toContain('// Generated by WC3 UI Designer');
      expect(content).toContain('Frame "BACKDROP" "BackdropOn" {');
      expect(content).toContain('BackdropBackground "tex.blp"');
      expect(content).toContain('UseActiveContext TRUE');
      expect(onShowAlert).toHaveBeenCalledWith(expect.objectContaining({ title: '成功' }));
    });

    it('uses default alert and enhanced mode with origin worldframe', async () => {
      dialogMocks.save.mockResolvedValue('out.fdf');
      fsMocks.writeTextFile.mockResolvedValue(undefined as never);
      fdfMocks.exportEnhanced.mockReturnValue('   Frame "Panel"\nSomeContent\n');
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      await exportToFDF(standardProject('worldframe'), true);
      expect(fdfMocks.exportEnhanced).toHaveBeenCalled();
      expect(fsMocks.writeTextFile).toHaveBeenCalled();
 // Header inserted before first 'Frame "'>0 occurrence
      const content = fsMocks.writeTextFile.mock.calls[0][1] as string;
      expect(content).toContain('Origin Mode: worldframe');
      expect(content).toContain('Frame "Panel"');
      expect(content).toContain('SomeContent');
      expect(alertSpy).toHaveBeenCalledWith(expect.stringContaining('增强模式'));
      vi.unstubAllGlobals();
    });

    it('prepends header when no Frame definition found (enhanced)', async () => {
      dialogMocks.save.mockResolvedValue('out.fdf');
      fsMocks.writeTextFile.mockResolvedValue(undefined as never);
      fdfMocks.exportEnhanced.mockReturnValue('No frames here at all');
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      await exportToFDF(standardProject('consoleui'), true);
      const content = fsMocks.writeTextFile.mock.calls[0][1] as string;
      expect(content.startsWith('// Origin Mode: consoleui')).toBe(true);
      expect(content).toContain('IncludeFile');
      expect(alertSpy).toHaveBeenCalled();
      vi.unstubAllGlobals();
    });

    it('enhanced success via onShowAlert reports 增强 mode suffix', async () => {
      dialogMocks.save.mockResolvedValue('out.fdf');
      fsMocks.writeTextFile.mockResolvedValue(undefined as never);
      fdfMocks.exportEnhanced.mockReturnValue('Frame "Panel"\n');
      const onShowAlert = vi.fn();
      await exportToFDF(standardProject('gameui'), true, onShowAlert);
      expect(onShowAlert).toHaveBeenCalledWith(
        expect.objectContaining({ title: '成功', message: expect.stringContaining('（增强模式）') })
      );
    });

    it('recurses and silently skips a child whose id is not in allFrames', async () => {
      dialogMocks.save.mockResolvedValue('out.fdf');
      fsMocks.writeTextFile.mockResolvedValue(undefined as never);
      const project = makeProject({ originMode: 'gameui', frames: {}, rootFrameIds: [] });
      const root = frame({ id: 'r', name: 'R', type: FrameType.FRAME, children: ['ghost'], anchors: [] });
      project.frames = { r: root };
      project.rootFrameIds = ['r'];
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      await exportToFDF(project, false);
      const content = fsMocks.writeTextFile.mock.calls[0][1] as string;
      expect(content).toContain('Frame "FRAME" "R" {');
      vi.unstubAllGlobals();
    });

    it('resolves project with unknown originMode to ConsoleUI via getParentName default', async () => {
      const project = makeProject({
        originMode: '' as ProjectData['originMode'],
        frames: {},
        rootFrameIds: [],
      });
      const root = frame({ id: 'r', name: 'R', type: FrameType.FRAME, anchors: [] });
      project.frames = { r: root };
      project.rootFrameIds = ['r'];
      dialogMocks.save.mockResolvedValue('out.fdf');
      fsMocks.writeTextFile.mockResolvedValue(undefined as never);
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      await exportToFDF(project, false);
      const content = fsMocks.writeTextFile.mock.calls[0][1] as string;
      expect(content).toContain('ConsoleUI');
      vi.unstubAllGlobals();
    });

    it('covers getParentName origin switch, getFrameTypeName cases, relativeTo target and parent-resolution', async () => {
      const tgt = frame({ id: 'tgt', name: 'TargetFrame', type: FrameType.HORIZONTAL_BAR, anchors: [] });
      const root2 = frame({
        id: 'root2', name: 'Root2', type: FrameType.FRAME,
        children: ['rel', 'plain', 'script', 'hor'],
      });
      const rel = frame({
        id: 'rel', name: 'RelChild', type: FrameType.TEXT_FRAME, parentId: 'root2',
        text: 't', horAlign: 'center', // no textScale -> fontSize default 0.012
        anchors: [{ point: FramePoint.TOPLEFT, relativeTo: 'tgt', relativePoint: FramePoint.BOTTOMRIGHT, x: 1, y: 2 }],
      });
      const plain = frame({ id: 'plain', name: 'Plain', type: FrameType.SLIDER, parentId: 'root2', anchors: [] });
      const script = frame({ id: 'script', name: 'ScriptBtn', type: FrameType.SCRIPT_DIALOG_BUTTON, parentId: 'root2', anchors: [] });
      const hor = frame({ id: 'hor', name: 'HorBar', type: FrameType.HORIZONTAL_BAR, parentId: 'root2', anchors: [] });
      const project = makeProject({
        originMode: 'gameui',
        frames: { root2, rel, plain, script, hor, tgt },
        rootFrameIds: ['root2'],
      });

 // worldframe root -> WorldFrameWar3
      const wf = makeProject({ originMode: 'worldframe', frames: {}, rootFrameIds: [] });
      const wfRoot = frame({ id: 'w', name: 'W', type: FrameType.FRAME, anchors: [] });
      wf.frames = { w: wfRoot };
      wf.rootFrameIds = ['w'];
 // consoleui root -> ConsoleUI
      const cu = makeProject({ originMode: 'consoleui', frames: {}, rootFrameIds: [] });
      const cuRoot = frame({ id: 'c', name: 'C', type: FrameType.FRAME, anchors: [] });
      cu.frames = { c: cuRoot };
      cu.rootFrameIds = ['c'];

      for (const p of [project, wf, cu]) {
        dialogMocks.save.mockResolvedValueOnce('out.fdf');
      }
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      await exportToFDF(project, false);
      await exportToFDF(wf, false);
      await exportToFDF(cu, false);

      const contents = fsMocks.writeTextFile.mock.calls.map((c) => c[1] as string);
      expect(contents.join('|')).toContain('WorldFrameWar3');
      expect(contents.join('|')).toContain('ConsoleUI');
 // parent resolution shows parent's name (TargetFrame is target of rel anchor not parent)
      expect(contents[0]).toContain('TargetFrame');
 // fontSize default 0.012 for text with horAlign but no textScale
      expect(contents[0]).toContain('FrameFont "MasterFont", 0.012');
 // getFrameTypeName cases
      expect(contents[0]).toContain('Frame "SLIDER" "Plain" {');
      expect(contents[0]).toContain('Frame "BUTTON" "ScriptBtn" {');
      expect(contents[0]).toContain('Frame "SLIDER" "HorBar" {');
      vi.unstubAllGlobals();
    });

    it('returns early when user cancels the save dialog', async () => {
      dialogMocks.save.mockResolvedValue(null as never);
      const onShowAlert = vi.fn();
      await exportToFDF(standardProject(), false, onShowAlert);
      expect(fsMocks.writeTextFile).not.toHaveBeenCalled();
      expect(onShowAlert).not.toHaveBeenCalled();
    });

    it('reports write failure through onShowAlert', async () => {
      dialogMocks.save.mockResolvedValue('out.fdf');
      fsMocks.writeTextFile.mockRejectedValue(new Error('disk full'));
      const onShowAlert = vi.fn();
      await exportToFDF(standardProject(), false, onShowAlert);
      expect(onShowAlert).toHaveBeenCalledWith(expect.objectContaining({ title: '错误', type: 'danger' }));
    });

    it('reports write failure through default alert when no callback', async () => {
      dialogMocks.save.mockResolvedValue('out.fdf');
      fsMocks.writeTextFile.mockRejectedValue(new Error('boom'));
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      const errSpy = vi.fn();
      vi.spyOn(console, 'error').mockImplementation(errSpy);
      await exportToFDF(standardProject(), false);
      expect(alertSpy).toHaveBeenCalled();
      expect(errSpy).toHaveBeenCalled();
      vi.unstubAllGlobals();
      (console.error as unknown as ReturnType<typeof vi.fn>).mockRestore();
    });
  });

  describe('exportToJSON', () => {
    it('writes pretty-printed JSON and reports success via onShowAlert', async () => {
      dialogMocks.save.mockResolvedValue('/out/project.json');
      fsMocks.writeTextFile.mockResolvedValue(undefined as never);
      const onShowAlert = vi.fn();
      const project = standardProject();
      await exportToJSON(project, onShowAlert);
      const [path, content] = fsMocks.writeTextFile.mock.calls[0] as [string, string];
      expect(path).toBe('/out/project.json');
      expect(JSON.parse(content)).toEqual(project);
      expect(onShowAlert).toHaveBeenCalledWith(expect.objectContaining({ title: '成功' }));
    });

    it('uses default alert on success and cancels dialog cleanly', async () => {
      dialogMocks.save.mockResolvedValue('project.json');
      fsMocks.writeTextFile.mockResolvedValue(undefined as never);
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      await exportToJSON(standardProject());
      expect(alertSpy).toHaveBeenCalledWith('导出 JSON 成功！');
      vi.unstubAllGlobals();

      vi.clearAllMocks();
      dialogMocks.save.mockResolvedValue(null as never);
      await exportToJSON(standardProject());
      expect(fsMocks.writeTextFile).not.toHaveBeenCalled();
    });

    it('reports failure through onShowAlert and default alert', async () => {
      dialogMocks.save.mockResolvedValue('project.json');
      fsMocks.writeTextFile.mockRejectedValue(new Error('fail'));
      const onShowAlert = vi.fn();
      await exportToJSON(standardProject(), onShowAlert);
      expect(onShowAlert).toHaveBeenCalledWith(expect.objectContaining({ title: '错误' }));

      fsMocks.writeTextFile.mockRejectedValue(new Error('fail2'));
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      await exportToJSON(standardProject());
      expect(alertSpy).toHaveBeenCalledWith(expect.stringContaining('导出失败'));
      vi.unstubAllGlobals();
    });
  });

  describe('exportToPNG', () => {
    interface FakeCanvas {
      toBlob: (cb: (blob: { arrayBuffer: () => Promise<ArrayBuffer> } | null) => void) => void;
    }
    function makeCanvasWithBlob(blob: { arrayBuffer: () => Promise<ArrayBuffer> } | null): FakeCanvas {
      return { toBlob: (cb) => cb(blob) };
    }
 // exportToPNG does not await the toBlob callback, and its body awaits a dynamic
 // import('@tauri-apps/plugin-fs') (a real module-resolution macrotask), so we flush
 // both microtasks and a macrotask before asserting on the tick.
    async function flush() {
      for (let i = 0; i < 20; i++) await Promise.resolve();
      await new Promise((r) => setTimeout(r, 0));
      for (let i = 0; i < 20; i++) await Promise.resolve();
    }

    it('handles null canvas via onShowAlert', async () => {
      const onShowAlert = vi.fn();
      await exportToPNG(null as never, onShowAlert);
      expect(onShowAlert).toHaveBeenCalledWith(expect.objectContaining({ title: '错误', message: '无法获取画布元素' }));
    });

    it('handles null canvas via default alert', async () => {
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      await exportToPNG(null as never);
      expect(alertSpy).toHaveBeenCalledWith('无法获取画布元素');
      vi.unstubAllGlobals();
    });

    it('cancels when save returns null', async () => {
      dialogMocks.save.mockResolvedValue(null as never);
      const canvas = { toBlob: () => { throw new Error('should not be called'); } };
      await exportToPNG(canvas as never);
      expect(dialogMocks.save).toHaveBeenCalledTimes(1);
    });

    it('reports blob generation failure via onShowAlert and default alert', async () => {
      dialogMocks.save.mockResolvedValue('out.png');
      const onShowAlert = vi.fn();
      await exportToPNG(makeCanvasWithBlob(null) as never, onShowAlert);
      await flush();
      expect(onShowAlert).toHaveBeenCalledWith(expect.objectContaining({ message: '生成图片失败' }));

      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      await exportToPNG(makeCanvasWithBlob(null) as never);
      await flush();
      expect(alertSpy).toHaveBeenCalledWith('生成图片失败');
      vi.unstubAllGlobals();
    });

    it('writes PNG successfully and reports via onShowAlert', async () => {
      dialogMocks.save.mockResolvedValue('out.png');
      fsMocks.writeFile.mockResolvedValue(undefined as never);
      const onShowAlert = vi.fn();
      const canvas = makeCanvasWithBlob({ arrayBuffer: async () => new ArrayBuffer(8) });
      await exportToPNG(canvas as never, onShowAlert);
      await flush();
      expect(fsMocks.writeFile).toHaveBeenCalledTimes(1);
      const [path, bytes] = fsMocks.writeFile.mock.calls[0] as [string, Uint8Array];
      expect(path).toBe('out.png');
      expect(bytes.byteLength).toBe(8);
      expect(onShowAlert).toHaveBeenCalledWith(expect.objectContaining({ title: '成功' }));
    });

    it('writes PNG and reports via default alert', async () => {
      dialogMocks.save.mockResolvedValue('out.png');
      fsMocks.writeFile.mockResolvedValue(undefined as never);
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      const canvas = makeCanvasWithBlob({ arrayBuffer: async () => new ArrayBuffer(1) });
      await exportToPNG(canvas as never);
      await flush();
      expect(alertSpy).toHaveBeenCalledWith('导出 PNG 成功！');
      vi.unstubAllGlobals();
    });

    it('reports write failure inside blob callback via onShowAlert and default alert', async () => {
      dialogMocks.save.mockResolvedValue('out.png');
      const onShowAlert = vi.fn();
      fsMocks.writeFile.mockRejectedValueOnce(new Error('io'));
      await exportToPNG(makeCanvasWithBlob({ arrayBuffer: async () => new ArrayBuffer(4) }) as never, onShowAlert);
      await flush();
      expect(onShowAlert).toHaveBeenCalledWith(expect.objectContaining({ title: '错误', type: 'danger' }));

      fsMocks.writeFile.mockRejectedValueOnce(new Error('io2'));
      const errSpy = vi.fn();
      vi.spyOn(console, 'error').mockImplementation(errSpy);
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      await exportToPNG(makeCanvasWithBlob({ arrayBuffer: async () => new ArrayBuffer(4) }) as never);
      await flush();
      expect(alertSpy).toHaveBeenCalled();
      expect(errSpy).toHaveBeenCalled();
      vi.unstubAllGlobals();
      (console.error as unknown as ReturnType<typeof vi.fn>).mockRestore();
    });

    it('reports outer save failure via onShowAlert and default alert', async () => {
      dialogMocks.save.mockRejectedValue(new Error('dialog err'));
      const onShowAlert = vi.fn();
      await exportToPNG({} as never, onShowAlert);
      expect(onShowAlert).toHaveBeenCalledWith(expect.objectContaining({ title: '错误' }));

      dialogMocks.save.mockRejectedValue(new Error('dialog err2'));
      const alertSpy = vi.fn();
      vi.stubGlobal('alert', alertSpy);
      await exportToPNG({} as never);
      await flush();
      expect(alertSpy).toHaveBeenCalled();
      vi.unstubAllGlobals();
    });
  });
});