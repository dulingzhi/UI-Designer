describe('checkSetAllPoints edge cases via exportFrame', () => {
  it('falls through to anchors when anchors length != 2', () => {
    const frame = mkFrame({
      id: 'f1',
      name: 'F',
      anchors: [{ point: FramePoint.CENTER, x: 0, y: 0 }],
    });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('SetPoint CENTER');
  });

  it('falls through to anchors when no TOPLEFT/BOTTOMRIGHT pair', () => {
    const frame = mkFrame({
      id: 'f1',
      name: 'F',
      anchors: [
        { point: FramePoint.TOPLEFT, x: 0, y: 0 },
        { point: FramePoint.TOPRIGHT, x: 0, y: 0 },
      ],
    });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('SetPoint');
  });

  it('falls through when 2 anchors have different relativeTo', () => {
    const frame = mkFrame({
      id: 'f1',
      name: 'F',
      anchors: [
        { point: FramePoint.TOPLEFT, relativeTo: 'a', x: 0, y: 0 },
        { point: FramePoint.BOTTOMRIGHT, relativeTo: 'b', x: 0, y: 0 },
      ],
    });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('SetPoint');
  });
});