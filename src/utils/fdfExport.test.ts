import { describe, it, expect } from 'vitest';
import { exportToFDF, exportFrameToFDF } from './fdfExport';
import { FrameData, FrameType, FramePoint } from '../types';

function mkFrame(partial: Partial<FrameData> & { name: string; id: string }): FrameData {
  return {
    type: FrameType.FRAME,
    x: 0,
    y: 0,
    width: 0,
    height: 0,
    z: 0,
    parentId: null,
    children: [],
    anchors: [],
    texture: '',
    ...partial,
  };
}

describe('exportToFDF', () => {
  it('exports empty array with comments header', () => {
    const out = exportToFDF([], {});
    expect(out).toContain('// Generated by WC3 UI Designer');
    expect(out).toContain('// Frame Definition File');
  });

  it('omits header when includeComments is false', () => {
    const out = exportToFDF([], { includeComments: false });
    expect(out).not.toContain('Generated by');
    expect(out).toBe('');
  });

  it('filters out non-top-level frames and separates top-level frames', () => {
    const parent = mkFrame({ id: 'p', name: 'Parent' });
    const child = mkFrame({ id: 'c', name: 'Child', parentId: 'p' });
    const out = exportToFDF([parent, child], { includeComments: false });
    expect(out).toContain('Frame "FRAME" "Parent" {');
    expect(out).not.toContain('Child');
  });

  it('inserts blank line between multiple top-level frames', () => {
    const a = mkFrame({ id: 'a', name: 'A', width: undefined, height: undefined });
    const b = mkFrame({ id: 'b', name: 'B', width: undefined, height: undefined });
    const out = exportToFDF([a, b], { includeComments: false });
    expect(out).toMatch(/Frame "FRAME" "A" \{\n\}\n\nFrame "FRAME" "B"/);
  });

  it('uses custom indent', () => {
    const frame = mkFrame({ id: 'p', name: 'Parent' });
    const out = exportToFDF([frame], { indent: '  ' });
    expect(out).toContain('Frame "FRAME" "Parent" {');
  });
});

describe('exportFrameToFDF / exportFrame details', () => {
  it('renders INHERITS WITHCHILDREN and template name', () => {
    const frame = mkFrame({
      id: 'f1',
      name: 'F',
      fdfMetadata: { inherits: 'Base', inheritedChildrenIds: ['a', 'b'] },
    });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('INHERITS WITHCHILDREN "Base"');
  });

  it('renders INHERITS without WITHCHILDREN', () => {
    const frame = mkFrame({ id: 'f1', name: 'F', fdfMetadata: { inherits: 'Base' } });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('INHERITS "Base"');
  });

  it('renders SetAllPoints with relative frame name when 2 matching anchors', () => {
    const parent = mkFrame({ id: 'p', name: 'Parent' });
    const child = mkFrame({
      id: 'c',
      name: 'Child',
      parentId: 'p',
      anchors: [
        { point: FramePoint.TOPLEFT, relativeTo: 'p', relativePoint: FramePoint.TOPLEFT, x: 0, y: 0 },
        { point: FramePoint.BOTTOMRIGHT, relativeTo: 'p', relativePoint: FramePoint.BOTTOMRIGHT, x: 0, y: 0 },
      ],
    });
    const out = exportFrameToFDF(child, [parent, child]);
    expect(out).toContain('SetAllPoints "Parent",');
  });

  it('renders SetAllPoints with fallback id when relative frame missing', () => {
    const child = mkFrame({
      id: 'c',
      name: 'Child',
      anchors: [
        { point: FramePoint.TOPLEFT, relativeTo: 'ghost', relativePoint: FramePoint.TOPLEFT, x: 0, y: 0 },
        { point: FramePoint.BOTTOMRIGHT, relativeTo: 'ghost', relativePoint: FramePoint.BOTTOMRIGHT, x: 0, y: 0 },
      ],
    });
    const out = exportFrameToFDF(child, [child]);
    expect(out).toContain('SetAllPoints "ghost",');
  });

  it('renders nothing for SetAllPoints when frame has no anchors', () => {
    const child = mkFrame({ id: 'c', name: 'Child' });
    const out = exportFrameToFDF(child, [child]);
    expect(out).not.toContain('SetPoint');
    expect(out).not.toContain('SetAllPoints');
  });

  it('handles frame with anchors undefined', () => {
    const child = mkFrame({ id: 'c', name: 'Child', anchors: undefined, width: undefined, height: undefined });
    const out = exportFrameToFDF(child, [child]);
    expect(out).not.toContain('SetPoint');
    expect(out).not.toContain('SetAllPoints');
  });

  it('omits Width/Height lines when undefined', () => {
    const child = mkFrame({ id: 'c', name: 'Child', width: undefined, height: undefined });
    const out = exportFrameToFDF(child, [child]);
    expect(out).not.toContain('Width ');
    expect(out).not.toContain('Height ');
  });

  it('renders bare SetAllPoints when anchors have no relativeTo', () => {
    const child = mkFrame({
      id: 'c',
      name: 'Child',
      anchors: [
        { point: FramePoint.TOPLEFT, x: 0, y: 0 },
        { point: FramePoint.BOTTOMRIGHT, x: 0, y: 0 },
      ],
    });
    const out = exportFrameToFDF(child, [child]);
    expect(out).toContain('SetAllPoints,');
  });

  it('renders individual anchors when not set-all-points', () => {
    const parent = mkFrame({ id: 'p', name: 'Parent' });
    const child = mkFrame({
      id: 'c',
      name: 'Child',
      parentId: 'p',
      anchors: [{ point: FramePoint.CENTER, relativeTo: 'p', relativePoint: FramePoint.CENTER, x: 1.5, y: 2.5 }],
    });
    const out = exportFrameToFDF(child, [parent, child]);
    expect(out).toContain('SetPoint CENTER, "Parent", CENTER, 1.5, 2.5,');
  });

  it('renders anchor with relativeTo that has no matching frame (uses id) and omitted relPoint', () => {
    const child = mkFrame({
      id: 'c',
      name: 'Child',
      anchors: [{ point: FramePoint.LEFT, relativeTo: 'missingId', x: 0, y: 0 }],
    });
    const out = exportFrameToFDF(child, [child]);
    expect(out).toContain('SetPoint LEFT, "missingId", LEFT, 0, 0,');
  });

  it('renders width/height and popup-specific properties', () => {
    const frame = mkFrame({
      id: 'f1',
      name: 'F',
      width: 0.5,
      height: 0.25,
      type: FrameType.POPUPMENU,
      popupButtonInset: 0.1,
      menuItemHeight: 0.2,
      menuBorder: 0.3,
      popupMenuFrameRef: 'MenuRef',
      popupArrowFrameRef: 'ArrowRef',
      popupTitleFrameRef: 'TitleRef',
    });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('Width 0.5,');
    expect(out).toContain('Height 0.25,');
    expect(out).toContain('PopupButtonInset 0.1,');
    expect(out).toContain('MenuItemHeight 0.2,');
    expect(out).toContain('MenuBorder 0.3,');
    expect(out).toContain('PopupMenuFrame "MenuRef",');
    expect(out).toContain('PopupArrowFrame "ArrowRef",');
    expect(out).toContain('PopupTitleFrame "TitleRef",');
  });

  it('renders MENU menuItemHeight and menuBorder quantity', () => {
    const frame = mkFrame({ id: 'f1', name: 'F', type: FrameType.MENU, menuItemHeight: 0.4, menuBorder: 0.5 });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('MenuItemHeight 0.4,');
    expect(out).toContain('MenuBorder 0.5,');
  });

  it('renders menuBorderRef when not menu/popupmenu with menuBorder undefined', () => {
    const frame = mkFrame({ id: 'f1', name: 'F', type: FrameType.FRAME, menuBorderRef: 'MB' });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('MenuBorder "MB",');
  });

  it('renders text properties and alignment/active context', () => {
    const frame = mkFrame({
      id: 'f1',
      name: 'F',
      text: 'Hello "World"',
      textScale: 1.5,
      textColor: '#ffffff',
      horAlign: 'center',
      verAlign: 'flex-end',
      useActiveContext: true,
    });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('Text "Hello \\"World\\"",');
    expect(out).toContain('TextScale 1.5,');
    expect(out).toContain('TextColor #ffffff,');
    expect(out).toContain('HorizontalAlignment "CENTER",');
    expect(out).toContain('VerticalAlignment "FLEX-END",');
    expect(out).toContain('UseActiveContext,');
  });

  it('does not emit default alignments (left/start) or textScale 1', () => {
    const frame = mkFrame({
      id: 'f1',
      name: 'F',
      textScale: 1,
      horAlign: 'left',
      verAlign: 'start',
    });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).not.toContain('TextScale');
    expect(out).not.toContain('HorizontalAlignment');
    expect(out).not.toContain('VerticalAlignment');
  });

  it('renders texture/backdrop properties', () => {
    const frame = mkFrame({
      id: 'f1',
      name: 'F',
      texture: 'bg.blp',
      backdropTileBackground: true,
      backdropEdgeFile: 'edge.blp',
      backdropCornerFlags: 'UL|UR',
      backdropCornerSize: 0.05,
      backdropBackgroundSize: 0.1,
      backdropBackgroundInsets: [1, 2, 3, 4] as any,
      backdropBlendAll: true,
    });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('BackdropBackground "bg.blp",');
    expect(out).toContain('BackdropTileBackground,');
    expect(out).toContain('BackdropEdgeFile "edge.blp",');
    expect(out).toContain('BackdropCornerFlags "UL|UR",');
    expect(out).toContain('BackdropCornerSize 0.05,');
    expect(out).toContain('BackdropBackgroundSize 0.1,');
    expect(out).toContain('BackdropBackgroundInsets 1 2 3 4,');
    expect(out).toContain('BackdropBlendAll,');
  });

  it('renders tooltip string only when a string', () => {
    const frame = mkFrame({ id: 'f1', name: 'F', tooltip: 'tip' as any });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('Tooltip "tip",');
  });

  it('does not render tooltip when boolean', () => {
    const frame = mkFrame({ id: 'f1', name: 'F', tooltip: true as any });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).not.toContain('Tooltip');
  });

  it('renders children and skips inherited child ids', () => {
    const parent = mkFrame({
      id: 'p',
      name: 'Parent',
      children: ['c1', 'c2'],
      fdfMetadata: { inheritedChildrenIds: ['c2'] },
    });
    const child1 = mkFrame({ id: 'c1', name: 'Child1', parentId: 'p' });
    const child2 = mkFrame({ id: 'c2', name: 'Child2', parentId: 'p' });
    const out = exportFrameToFDF(parent, [parent, child1, child2]);
    expect(out).toContain('Child1');
    expect(out).not.toContain('Child2');
  });

  it('does not push child block when all children are inherited', () => {
    const parent = mkFrame({
      id: 'p',
      name: 'Parent',
      children: ['c1'],
      fdfMetadata: { inheritedChildrenIds: ['c1'] },
    });
    const child1 = mkFrame({ id: 'c1', name: 'Child1', parentId: 'p' });
    const out = exportFrameToFDF(parent, [parent, child1]);
    // inherited child is entirely skipped; no empty '' line inside braces
    expect(out).not.toContain('Child1');
  });

  it('skips child ids with no matching frame', () => {
    const parent = mkFrame({ id: 'p', name: 'Parent', children: ['ghost'] });
    const out = exportFrameToFDF(parent, [parent]);
    expect(out).not.toContain('ghost');
  });

  it('recursively exports children at deeper indent', () => {
    const parent = mkFrame({ id: 'p', name: 'Parent', children: ['c1'] });
    const child1 = mkFrame({ id: 'c1', name: 'Child1', parentId: 'p', children: ['g1'] });
    const g1 = mkFrame({ id: 'g1', name: 'GrandChild', parentId: 'c1', width: 1 });
    const out = exportFrameToFDF(parent, [parent, child1, g1]);
    expect(out).toContain('GrandChild');
  });
});

describe('formatNumber and escapeString behaviors via export', () => {
  it('formats numbers removing trailing zeros', () => {
    const frame = mkFrame({ id: 'f1', name: 'F', width: 1.0, height: 0.100000 });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('Width 1,');
    expect(out).toContain('Height 0.1,');
  });

  it('escapes special characters', () => {
    const frame = mkFrame({ id: 'f1', name: 'F', text: 'a\\b"c\nd\re\tf' });
    const out = exportFrameToFDF(frame, [frame]);
    expect(out).toContain('Text "a\\\\b\\"c\\nd\\re\\tf",');
  });
});

